# Design note (why this prompt is written the way it is):
#
# The naive failure mode for Banglish -> Bangla transliteration is
# "phonetic/letter-by-letter" conversion — the model maps English letters to
# their closest-sounding Bangla letters without checking whether the
# resulting word actually exists. This produces plausible-looking but wrong
# output (e.g. "doman" -> "ডোমান" instead of "দমন") because Banglish is
# ambiguous at the letter level: the same Roman spelling can map to several
# different Bangla spellings, and only *meaning* disambiguates it.
#
# The fix below is NOT a list of specific words to memorize. It re-frames the
# task itself: the model is instructed to transliterate by first recovering
# the *intended Bangla word from context/meaning*, then writing that word's
# standard dictionary spelling — never inventing a spelling just because it
# sounds close. The few-shot examples exist only to demonstrate this
# *process* across varied, unrelated words (not just agricultural terms), so
# the model generalizes the pattern instead of pattern-matching on a fixed
# vocabulary list.

